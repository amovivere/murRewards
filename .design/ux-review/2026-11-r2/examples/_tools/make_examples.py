def shot(src, out, kicker, title, lead, items):
    a = Annotator(os.path.join(PACK, src), title, kicker, lead)
    for n, color, t, sub, marks in items:
        a.add(n, color, t, sub, marks)
    path = os.path.join(EX, out)
    a.render(path)
    print("ok", out)


